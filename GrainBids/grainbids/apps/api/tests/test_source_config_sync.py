"""Guard against drift between config.toml and us_elevators_urls.toml.

``us_elevators_urls.toml`` is the canonical list of US elevator cash-bid
sources. ``config.toml`` carries a copy of that list under ``[us]`` for
the legacy GrainBidder runner, generated by
``scripts/sync_us_elevators_config.py``. The two drifted apart before
(Cycle 17 audit: config.toml had only 30 of the 121 entries, plus 4 type
mismatches), so this test fails loudly if they ever diverge again.

Stdlib only (``tomllib``) — no app imports, so it also runs when the
FastAPI app cannot be imported.
"""

from __future__ import annotations

import tomllib
import unittest
from pathlib import Path

SOURCES_DIR = (
    Path(__file__).resolve().parents[1]
    / "app"
    / "platform"
    / "market_data"
    / "sources"
)
CONFIG_PATH = SOURCES_DIR / "config.toml"
URLS_PATH = SOURCES_DIR / "us_elevators_urls.toml"

# The whole entry: nothing else may appear in a [[us.elevators]] block.
ENTRY_FIELDS = ("name", "url", "type", "enabled")


def _elevators(path: Path) -> list[dict]:
    with path.open("rb") as fh:
        return tomllib.load(fh)["us"]["elevators"]


class SourceConfigSyncTests(unittest.TestCase):
    def test_us_elevators_lists_match(self) -> None:
        """config.toml [[us.elevators]] is a faithful copy of the urls toml."""
        config_entries = _elevators(CONFIG_PATH)
        urls_entries = _elevators(URLS_PATH)
        self.assertEqual(
            len(config_entries),
            len(urls_entries),
            f"config.toml has {len(config_entries)} [[us.elevators]] entries, "
            f"us_elevators_urls.toml has {len(urls_entries)} — "
            "re-run scripts/sync_us_elevators_config.py",
        )
        for index, (config_entry, urls_entry) in enumerate(
            zip(config_entries, urls_entries)
        ):
            for field in ENTRY_FIELDS:
                self.assertEqual(
                    config_entry.get(field),
                    urls_entry.get(field),
                    f"entry {index} ({urls_entry.get('name')!r}): {field} "
                    f"differs between config.toml and us_elevators_urls.toml",
                )

    def test_no_extra_fields_and_no_duplicate_names(self) -> None:
        """Entries carry exactly name/url/type/enabled, keyed by unique name."""
        for path in (CONFIG_PATH, URLS_PATH):
            entries = _elevators(path)
            names = [entry.get("name") for entry in entries]
            self.assertEqual(
                len(names),
                len(set(names)),
                f"{path.name} has duplicate [[us.elevators]] names",
            )
            for entry in entries:
                self.assertEqual(
                    sorted(entry),
                    sorted(ENTRY_FIELDS),
                    f"{path.name} entry {entry.get('name')!r} has unexpected fields: "
                    f"{sorted(set(entry) - set(ENTRY_FIELDS))}",
                )

    def test_config_section_is_marked_generated(self) -> None:
        """The config.toml copy carries the generated header from the sync script."""
        text = CONFIG_PATH.read_text(encoding="utf-8")
        self.assertIn("GENERATED — DO NOT EDIT BY HAND", text)
        self.assertIn(
            "Synced from us_elevators_urls.toml by scripts/sync_us_elevators_config.py",
            text,
        )
        self.assertIn("us_elevators_urls.toml is canonical", text)


if __name__ == "__main__":
    unittest.main()
